-- ——— статистика (внутренняя) ———

-- Асыки, сыгранные и выигранные матчи на асыки всех игроков (кроме заблокированных).
-- Сыгран — матч дошёл до раздачи (settled). Победа — выбил больше, чем каждый соперник, и не сдался;
-- ничья (поровну, в том числе 0 : 0) победой не считается.
create or replace function private.player_stats()
  returns table (id uuid, player_no bigint, name text, asyks bigint, wins bigint, played bigint)
  language sql stable security definer set search_path = ''
as $$
  with games as (
    select p.user_id, p.knocked, p.forfeited,
           (select max(o.knocked) from public.comp_players o
             where o.match_id = p.match_id and o.user_id <> p.user_id) as best_other
    from public.comp_players p
    join public.comp_matches m on m.id = p.match_id
    where m.status = 'settled'
  )
  select pr.id,
         pr.player_no,
         coalesce(pr.nickname, 'Игрок ' || pr.player_no::text) as name,
         (select count(*) from public.asyks a where a.owner = pr.id) as asyks,
         (select count(*) from games g
           where g.user_id = pr.id and not g.forfeited and g.knocked > coalesce(g.best_other, 0)) as wins,
         (select count(*) from games g where g.user_id = pr.id) as played
  from public.profiles pr
  where not pr.banned
$$;

-- ——— функции для игроков ———

-- Рейтинг: p_sort — 'asyks' | 'wins' | 'played'. Возвращает
-- {sort, total, rows: [{place, player_no, name, asyks, wins, played, me}], me: {...} | null}.
-- Внутренний uuid наружу не отдаётся: только номер игрока (player_no) и ник.
-- Места — «спортивные»: при равенстве одно место (1, 1, 3). me — строка вызывающего, даже если он не в топе.
create or replace function public.leaderboard(p_sort text default 'asyks', p_limit int default 50) returns jsonb
  language plpgsql stable security definer set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_limit int := least(greatest(coalesce(p_limit, 50), 1), 100);
  v_res jsonb;
begin
  if p_sort is null or p_sort not in ('asyks', 'wins', 'played') then
    raise exception 'bad_sort' using errcode = 'P0001';
  end if;

  with ranked as (
    select s.id, s.player_no, s.name, s.asyks, s.wins, s.played,
           rank() over (order by case p_sort when 'asyks' then s.asyks when 'wins' then s.wins else s.played end desc) as place
    from private.player_stats() s
  ),
  top as (
    select r.* from ranked r order by r.place, r.player_no limit v_limit
  )
  select jsonb_build_object(
    'sort', p_sort,
    'total', (select count(*) from ranked),
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
                        'place', t.place, 'player_no', t.player_no, 'name', t.name,
                        'asyks', t.asyks, 'wins', t.wins, 'played', t.played,
                        'me', v_uid is not null and t.id = v_uid) order by t.place, t.player_no)
                      from top t), '[]'::jsonb),
    'me', (select jsonb_build_object(
                    'place', r.place, 'player_no', r.player_no, 'name', r.name,
                    'asyks', r.asyks, 'wins', r.wins, 'played', r.played, 'me', true)
           from ranked r where v_uid is not null and r.id = v_uid))
    into v_res;
  return v_res;
end;
$$;

-- Мой профиль для страницы аккаунта: {nickname, name, player_no, asyks, free, locked, wins, played}.
create or replace function public.my_profile() returns jsonb
  language plpgsql stable security definer set search_path = ''
as $$
declare
  v_uid uuid := private.comp_caller();
  v_s record;
  v_nick text;
begin
  select s.* into v_s from private.player_stats() s where s.id = v_uid;
  select pr.nickname into v_nick from public.profiles pr where pr.id = v_uid;
  return jsonb_build_object(
    'nickname', v_nick,
    'name', v_s.name,
    'player_no', v_s.player_no,
    'asyks', coalesce(v_s.asyks, 0),
    'free', (select count(*) from public.asyks a where a.owner = v_uid and a.locked_match is null),
    'locked', (select count(*) from public.asyks a where a.owner = v_uid and a.locked_match is not null),
    'wins', coalesce(v_s.wins, 0),
    'played', coalesce(v_s.played, 0));
end;
$$;

-- Сменить ник (пустая строка — убрать ник, в рейтинге снова «Игрок N»). Возвращает my_profile().
-- Ошибки: nick_short, nick_chars, nick_reserved, nick_taken, rate_limited.
create or replace function public.set_nickname(p_name text) returns jsonb
  language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_uid uuid := private.comp_caller();
  v_name text := private.comp_clean_name(p_name, '');
  v_at timestamptz;
begin
  select pr.nickname_at into v_at from public.profiles pr where pr.id = v_uid for update;
  if v_at is not null and v_at > now() - interval '10 seconds' then
    raise exception 'rate_limited' using errcode = 'P0001';
  end if;

  if v_name = '' then
    update public.profiles pr set nickname = null, nickname_at = now() where pr.id = v_uid;
    return public.my_profile();
  end if;
  if char_length(v_name) < 2 then
    raise exception 'nick_short' using errcode = 'P0001';
  end if;
  -- буквы любого алфавита, цифры, пробел, точка, дефис, подчёркивание
  if v_name !~ '^[[:alnum:] ._-]+$' or v_name !~ '[[:alpha:]]' then
    raise exception 'nick_chars' using errcode = 'P0001';
  end if;
  -- не выдавать себя за «Игрока N» и за администрацию
  if v_name ~* '^(игрок|player|ойыншы)[ ._-]*[0-9]*$' or v_name ~* '(admin|админ|модератор|moderator)' then
    raise exception 'nick_reserved' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.profiles pr where lower(pr.nickname) = lower(v_name) and pr.id <> v_uid) then
    raise exception 'nick_taken' using errcode = 'P0001';
  end if;

  begin
    update public.profiles pr set nickname = v_name, nickname_at = now() where pr.id = v_uid;
  exception when unique_violation then
    raise exception 'nick_taken' using errcode = 'P0001';
  end;
  return public.my_profile();
end;
$$;

