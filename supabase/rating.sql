-- «Асық ату»: ник игрока и рейтинг (страница «Рейтинг»).
--
-- Как применить: SQL Editor → New query → вставить весь файл → Run (после schema.sql и competitive.sql).
-- Скрипт можно запускать повторно: он ничего не удаляет и не дублирует.
--
-- Безопасность:
--   * в рейтинге только ник (или «Игрок N»), число асыков, побед и сыгранных матчей — ни почты, ни id;
--   * ник меняет только сам игрок через set_nickname (проверка длины, символов и занятости — здесь, в базе);
--   * всё считает база по своим таблицам: подделать асыки, победы или игры из браузера нельзя;
--   * рейтинг можно смотреть и без входа (функция leaderboard открыта для anon — в ней нет личных данных).

-- ——— профиль: ник и номер игрока ———

alter table public.profiles
  add column if not exists nickname text,
  add column if not exists nickname_at timestamptz;
-- номер игрока для «Игрок N»: существующим профилям раздаётся по порядку при первом запуске
alter table public.profiles
  add column if not exists player_no bigint generated by default as identity;
create unique index if not exists profiles_player_no_idx on public.profiles (player_no);
-- ник уникален без учёта регистра
create unique index if not exists profiles_nickname_idx on public.profiles (lower(nickname)) where nickname is not null;
alter table public.profiles drop constraint if exists profiles_nickname_check;
alter table public.profiles add constraint profiles_nickname_check
  check (nickname is null or char_length(nickname) between 2 and 16);

