  /** Максимальный кадр, который «догоняем» (после сворачивания вкладки и т.п.). */
  maxFrameMs: 100,

  /**
   * Трение о землю — ПОСТОЯННОЕ замедление (кулоново трение, μ·g).
   * В отличие от «вязкого» frictionAir, объект останавливается за конечное
   * время и не «плывёт» бесконечно на малой скорости.
   */
  decel: { saka: 0.34, asyk: 0.3 },
  /** Небольшое дополнительное линейное затухание (сопротивление, неровности асфальта). */
  linearDamping: 0.012,
  /** Замедление вращения (рад / (1/60 с)²) и его затухание. */
  angularDecel: 0.0022,
  angularDamping: 0.035,
  /** Ниже этой скорости тело считаем остановившимся и обнуляем скорость. */
